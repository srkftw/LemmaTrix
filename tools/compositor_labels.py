"""Derive the trusted compositor's used text table from the canonical labels."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
IDS=(0,4,5,6,7,8,14,20,32,33,34,36,50,51,52,53,54,55,56,57)
def generated():
 source=(ROOT/'Guest/Labels.lean').read_text()
 out=['import Guest.Raster','namespace Guest.CompositorLabels','open Guest.LiveSDK','-- Generated by tools/compositor_labels.py from the unchanged canonical label IDs.','-- Only these20 labels are reachable in the trusted compositor.','def say (id x y fg bg t : UInt64) : UInt64 :=']
 for number in IDS:
  found=re.search(r'  if id == '+str(number)+r' then\n(.*?Guest\.Raster\.text[^\n]+)',source,re.S)
  if found is None:raise ValueError('missing canonical label'+str(number))
  out+=['  if id == '+str(number)+' then',found[1],'  else']
 return '\n'.join(out+['    t','end Guest.CompositorLabels',''])
if __name__=='__main__':
 import argparse
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 target=ROOT/'Guest/CompositorLabels.lean';data=generated()
 if a.check:
  if target.read_text()!=data:raise SystemExit('Compositor labels differ from canonical labels; regenerate with python3 tools/compositor_labels.py')
  print('Compositor20-label subset equals canonical labels')
 else:target.write_text(data)
